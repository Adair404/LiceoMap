const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
module.exports = async ({call,evaluate,navigate,until,screenshot,web}) => {
    const accounts = JSON.parse(fs.readFileSync(path.resolve(web,'../.local/liceomap_preoficial_test.accounts.json'),'utf8'));
    const account = rut => accounts.find(a => a.rut === rut);
    const submit = async (rut,password) => {
        await evaluate(`document.querySelector('#admin-rut').value=${JSON.stringify(rut)};
            document.querySelector('#admin-pass').value=${JSON.stringify(password)};
            document.querySelector('#admin-login-form').requestSubmit()`);
        await until(() => evaluate("!document.querySelector('#admin-login-form button[type=submit]').disabled"),'login completed');
    };
    await navigate();
    await until(() => evaluate("document.querySelector('#app-preloader').hidden"),'intro');
    await evaluate("localStorage.setItem('liceomap_session',JSON.stringify({rol:'dev'})); setDashboardVisible(true)");
    assert(await evaluate("document.querySelector('#admin-dashboard').hidden"));
    await evaluate("document.querySelector('#btn-open-admin').click()");
    await submit('20100002-5','incorrecta');
    assert(await evaluate("document.querySelector('#admin-dashboard').hidden"));
    await submit(account('20100006-8').rut,account('20100006-8').password);
    assert(await evaluate("document.querySelector('#admin-dashboard').hidden"));
    assert((await evaluate("document.querySelector('#admin-login-status').textContent")).includes('rol'));
    await submit(account('20100002-5').rut,account('20100002-5').password);
    assert.equal(await evaluate("document.querySelector('#admin-dashboard').hidden"),false);
    await until(() => evaluate("document.querySelector('#announcement-list-status').textContent.includes('anuncio(s)')"),'real list');
    assert((await evaluate("document.querySelector('#admin-user-name').textContent")).includes('utp'));
    assert.equal(await evaluate("document.querySelectorAll('.admin-tab-btn:disabled').length"),3);
    const title = 'Web sincronización ' + Date.now();
    await evaluate(`document.querySelector('#demo-announcement-title').value=${JSON.stringify(title)};
        document.querySelector('#demo-announcement-body').value='<img src=x onerror=alert(1)> Texto literal';
        document.querySelector('#announcement-form').requestSubmit()`);
    await until(() => evaluate("!document.querySelector('#announcement-save').disabled"),'saved');
    assert.equal(await evaluate("document.querySelector('#announcement-status').textContent"),'Anuncio publicado.');
    const aid = await evaluate(`[...document.querySelectorAll('.announcement-item')].find(n=>n.querySelector('h4').textContent===${JSON.stringify(title)}).dataset.announcementId`);
    assert.equal(await evaluate("document.querySelectorAll('#announcement-list img').length"),0);
    await evaluate(`document.querySelector('[data-announcement-id="${aid}"] button').click();document.querySelector('#demo-announcement-title').value='Editado desde web';document.querySelector('#announcement-form').requestSubmit()`);
    await until(() => evaluate("!document.querySelector('#announcement-save').disabled"),'edited');
    assert.equal(await evaluate(`document.querySelector('[data-announcement-id="${aid}"] h4').textContent`),'Editado desde web');
    await call('Page.handleJavaScriptDialog',{accept:true}).catch(()=>{});
    await evaluate('window.confirm=()=>true');
    await evaluate(`document.querySelectorAll('[data-announcement-id="${aid}"] button')[1].click()`);
    await until(() => evaluate(`!document.querySelector('[data-announcement-id="${aid}"] button')`),'withdrawn');
    await screenshot('preoficial-admin');
    await evaluate("document.querySelector('#btn-logout-admin').click();setDashboardVisible(true)");
    assert(await evaluate("document.querySelector('#admin-dashboard').hidden"));
    assert.equal(await evaluate("document.querySelectorAll('#announcement-list article').length"),0);
    assert.equal(await evaluate("Object.keys(sessionStorage).length"),0);
    assert.equal(await evaluate("localStorage.getItem('liceomap_session')"),null);
    console.log('PASS: real web login, denied student, no forged session, create/edit/withdraw, XSS escaping, logout, disabled future tools.');
};
